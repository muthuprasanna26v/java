public class ConstantExample {
    public static void main(String[] args) {
        final int MAXIMUM_SCORE = 100;
        final int PASSING_MARKS = 40;
        final double PI = 3.14159;
        final String COUNTRY_NAME = "India";
        
        System.out.println("Maximum score: " + MAXIMUM_SCORE);
        System.out.println("Passing marks: " + PASSING_MARKS);
        System.out.println("PI: " + PI);
        System.out.println("Country: " + COUNTRY_NAME);
    }
}
